// Source: main.gold_mls.search_listings, pulled 2026-09-07, filtered
//   state='ID' AND global_filter_residential_sales_on_mls = true
//   AND property_type_aggregated = 'Single Family' AND sale_status = 'SOLD'
// Price = coalesce(close_price, current_price). close_price is only ~50%
// populated on Boise inventory; current_price is complete and matches
// close_price exactly wherever both exist (verified 101/101 and 15/15).
//
// NEW vs RESALE USES A ROLLING VINTAGE: built in the sale year or the one
// before = new, everything else = resale. This deliberately does NOT match
// the IMLS report's fixed "year built >= 2025" threshold, which double-counts
// 2025-built homes into 2026 and inflates new-construction growth. ZIP figures
// therefore will not tie exactly to the area tables' new/existing split.
//
// Windows are month-agnostic in the data and labelled from BOISE_ZIP_PERIOD
// below, so a refresh is a data swap plus one constant \u2014 no label edits.
//   mo*    = the reporting month (Aug 2026)
//   ytd*   = Jan 1 - Aug 31 2026;  ytd25* = the same window in 2025
//   ttm*   = 12 full months, Sep 1 2025 - Aug 31 2026
//   active/pending = live counts at pull time, not period figures
//
// NOTE ON THE TTM WINDOW: the previous (July) pull ran TTM open-ended from its
// start date to the pull timestamp, so it swept in three partial weeks of a
// 13th month. This pull closes the window at the month boundary. The effect on
// the medians is small, but TTM counts will not tie exactly to the July file.
const BOISE_ZIP_PERIOD = {
  month: 'Aug-26',            // compact column and table label
  monthLong: 'August 2026',   // prose
  ytd: 'Jan 1 \u2013 Aug 31 2026',
  ytdPrior: 'Jan 1 \u2013 Aug 31 2025',
  ttm: 'Sep 2025 \u2013 Aug 2026',
  pulled: '2026-09-07',
};

